for col_idx in [6, 12, 13]:
    requests.append({
        'repeatCell': {
            'range': {'sheetId': sid, 'startRowIndex': 1, 'startColumnIndex': col_idx, 'endColumnIndex': col_idx + 1},
            'cell': {'userEnteredFormat': {'wrapStrategy': 'WRAP'}},
            'fields': 'userEnteredFormat.wrapStrategy',
        }
    })

