#!/usr/bin/env python3
"""キルスイッチ（時事枠の停止判定）の誤作動を防ぐテスト。

## なぜこのファイルがあるか

同じ種類の誤作動を三度起こしている。

  2026-08-04〜17  「特別警報の発表はなく…津波警報…もなし」を災害と誤読し、
                  2週間ぶんの時事文脈が使えなかった
  2026-08-24      「気象特別警報・警報・注意報」という**文書名**を災害と誤読し、
                  重大災害の通知メールを誤送信した
  2026-09-01      「…津波警報・噴火警戒レベル4以上…は確認されなかった」を
                  災害と誤読した（Mac mini 移設の初回実行）

いずれも「危険語が“無かったこと”の説明として現れる」形である。平常時の根拠文は
むしろこの形で危険語を並べるため、素朴な部分一致では毎回引っかかる。

その都度パターンを足してきたが、テストを残していなかったので再発に気づけなかった。
**新しい言い回しで誤作動したら、まずここに1行足してから直すこと。**

    /usr/bin/python3 test_kill_switch.py
"""

import sys

from collect_context import kill_hits, severe_hits

# (根拠文, 止まるべきか, 何の事例か)
CASES = [
    # ── 平常時。止まってはいけない ──────────────────────────
    ("特別警報の発表はなく、津波警報・噴火警戒レベル4以上の発表もなし",
     False, "2026-08-04 の誤作動: 「はなく」「もなし」"),

    ("9/1時点で全国的な警報の発令は確認できず、三重県の一部で大雨・雷注意報が"
     "継続している程度で、特別警報・震度6弱以上・津波警報・噴火警戒レベル4以上・"
     "広域死者行方不明災害は確認されなかった",
     False, "2026-09-01 の誤作動: 「確認できず」「確認されなかった」"),

    ("気象特別警報・警報・注意報の一覧を確認したが、発表中のものはない",
     False, "2026-08-24 の誤作動: 文書名を災害と読んだ"),

    ("噴火警戒レベルは全山で1を維持しており、津波の心配もありません",
     False, "文書名＋否定の複合"),

    ("特別警報は出ていません。震度6以上の地震も発生していません",
     False, "丁寧形の否定"),

    ("全国的に警報級の現象はゼロ、いずれも注意報にとどまる",
     False, "ゼロ・注意報のみ"),

    # ── 実際に起きている。必ず止まる ────────────────────────
    ("鹿児島県に大雨特別警報が発表されました",
     True, "特別警報が実際に出ている"),

    ("午前3時に震度6弱の地震が発生し、津波警報が発表されている",
     True, "地震と津波が実際に起きている"),

    ("桜島の噴火警戒レベルが4に引き上げられ、避難指示が出ている",
     True, "噴火警戒レベル引き上げ"),

    # ── 節ごとの判定が効くか ────────────────────────────────
    ("震度6弱の地震が発生し、けが人はいない",
     True, "後半だけ否定。前半の事実で止まるべき"),

    ("大雨警報が発表中だが、特別警報には至っていない",
     True, "前半に実際の警報がある"),
]


def main() -> int:
    ng = 0
    for reason, should_stop, label in CASES:
        hits = kill_hits({"根拠": reason, "重大災害": {}})
        stopped = bool(hits)
        ok = stopped == should_stop
        if not ok:
            ng += 1
        mark = "  " if ok else "NG"
        want = "止まる" if should_stop else "通す"
        got = "止まった" if stopped else "通した"
        print(f"{mark} [{want}→{got}] {label}")
        if not ok:
            print(f"     根拠: {reason[:70]}")
            print(f"     検知語: {hits}")

    # Lv2（メール通知）は Lv1 より厳しく、平常時に鳴ってはならない。
    # 2026-08-24 は Lv1 が通したのに Lv2 だけ鳴って誤送信した。
    print()
    for reason, should_stop, label in CASES:
        if should_stop:
            continue
        sev = severe_hits({"根拠": reason, "重大災害": {}})
        if sev:
            ng += 1
            print(f"NG [通報しない→通報した] {label}")
            print(f"     検知語: {sev}")
    if ng == 0:
        print("Lv2（通知）も平常時に鳴りませんでした")

    print()
    print(f"{'✅ 全て通過' if ng == 0 else f'❌ {ng}件 失敗'}（{len(CASES)}件中）")
    return 1 if ng else 0


if __name__ == "__main__":
    raise SystemExit(main())
