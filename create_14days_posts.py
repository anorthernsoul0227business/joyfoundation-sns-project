x_next = len(x_data) + 1

x_rows = []
for i, day in enumerate(DAYS):
    dt = START_DATE + timedelta(days=i)
    dt_str = f"{dt.strftime('%Y/%m/%d')} {day['x_time']}:00"
    text = day['x_text']
    count = x_count(text)

    if count > 280:
        print(f"  ⚠️ Day {i+1} 文字数超過: {count}/280")

    x_rows.append([
        dt_str,           # A: 投稿日時
        text,             # B: 投稿テキスト
        '',               # C: 画像1
        '',               # D: 画像リンク1
        '',               # E: 画像2
        '',               # F: 画像リンク2
        '',               # G: 画像3
        '',               # H: 画像リンク3
        '下書き',          # I: ステータス
        f'{day["theme"]}',  # J: メモ
        '',               # K: リプライテキスト
    ])
    print(f"  Day {i+1} ({dt.strftime('%m/%d')}) [{day['theme']}] {count}/280文字")

x_end = x_next + len(x_rows) - 1
x_ws.update(
    values=x_rows,
    range_name=f'A{x_next}:K{x_end}',
    value_input_option='USER_ENTERED',
)
print(f"  → Row {x_next}〜{x_end} に追加 (ステータス: 下書き)")

