def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--show", action="store_true", help="タブを表示する（既定は非表示）")
    args = ap.parse_args()

    gc = gspread.service_account(
        filename=os.path.expanduser("~/.config/gspread/service_account.json"))
    sh = gc.open_by_key(SPREADSHEET_KEY)

    try:
        ws = sh.worksheet(TAB)
        ws.clear()
    except gspread.WorksheetNotFound:
        ws = sh.add_worksheet(title=TAB, rows=200, cols=len(HEADER))

    rows = [HEADER]
    for d, name, place, tm, fee, apply_, src, memo in EVENTS:
        dt = date.fromisoformat(d)
        rows.append([d, W[dt.weekday()], name, place, tm, fee, apply_, src, "", memo])

    ws.update(values=rows, range_name="A1")
    ws.format("A1:J1", {"textFormat": {"bold": True},
                        "backgroundColor": {"red": .92, "green": .92, "blue": .92}})
    ws.freeze(rows=1)
    ws.unhide() if args.show else ws.hide()

    print(f"✅ {TAB}: {len(EVENTS)}件を書き込みました（{'表示' if args.show else '非表示'}）")
    l1 = sum(1 for e in EVENTS if "L1" in e[6])
    print(f"   うち原本(L1)で裏が取れているもの: {l1}件")
    print(f"   残りは共有カレンダー(L4)のみが根拠。圭一郎さん確認欄で裏取りしてください。")


if __name__ == "__main__":
    main()
