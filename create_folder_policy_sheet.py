def main():
    gc = gspread.service_account(
        filename=os.path.expanduser("~/.config/gspread/service_account.json"))
    sh = gc.open_by_key(KEY)
    try:
        ws = sh.worksheet(TAB)
        ws.clear()
    except gspread.WorksheetNotFound:
        ws = sh.add_worksheet(title=TAB, rows=60, cols=len(HEADER))

    values = [HEADER] + [[f, n, k, g, why, "", ask] for f, n, k, g, why, ask in ROWS]
    ws.update(values=values, range_name="A1")
    ws.format("A1:G1", {"textFormat": {"bold": True},
                        "backgroundColor": {"red": .92, "green": .92, "blue": .92}})
    ws.freeze(rows=1)
    sh.batch_update({"requests": [
        {"updateSheetProperties": {
            "properties": {"sheetId": ws.id, "hidden": False}, "fields": "hidden"}},
        {"updateDimensionProperties": {
            "range": {"sheetId": ws.id, "dimension": "COLUMNS", "startIndex": 4, "endIndex": 5},
            "properties": {"pixelSize": 380}, "fields": "pixelSize"}},
        {"updateDimensionProperties": {
            "range": {"sheetId": ws.id, "dimension": "COLUMNS", "startIndex": 6, "endIndex": 7},
            "properties": {"pixelSize": 320}, "fields": "pixelSize"}},
    ]})

    total = sum(r[1] for r in ROWS)
    by = {}
    for r in ROWS:
        by[r[3]] = by.get(r[3], 0) + r[1]
    print(f"✅ {TAB}: {len(ROWS)}フォルダ / {total}枚")
    for k, v in sorted(by.items(), key=lambda x: -x[1]):
        print(f"   汎用性 {k}: {v}枚")
    print(f"   伺いたいことがある行: {sum(1 for r in ROWS if r[5])}")
    print(f"\n   https://docs.google.com/spreadsheets/d/{KEY}/edit#gid={ws.id}")


if __name__ == "__main__":
    main()
